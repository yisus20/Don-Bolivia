// Función para construir los productos con referencias completas
function buildProducts(): Product[] {
  return RAW_PRODUCTS.map((raw, index) => {
    const brandId = BRAND_NAME_MAP[raw.brand] || 'brand-donner'
    const categoryId = CATEGORY_SLUG_MAP[raw.category] || 'cat-otros'
    const brand = STATIC_BRANDS.find(b => b.id === brandId)
    const category = STATIC_CATEGORIES.find(c => c.id === categoryId)

    const images: ProductImage[] = (raw.images || []).map((img, imgIndex) => ({
      id: `img-${raw.id}-${imgIndex}`,
      product_id: raw.id,
      url: img.url,
      alt_text: img.alt_text || raw.name,
      order: img.order,
      is_primary: img.is_primary,
      created_at: '2025-01-01T00:00:00Z',
    }))

    const realInstrument = images.find(i => !i.url.includes('_img00.jpeg'));
    const primaryImage = images.find(i => i.is_primary && !i.url.includes('_img00.jpeg')) || realInstrument || images.find(i => i.is_primary)

    return {
      id: raw.id,
      name: raw.name,
      slug: raw.slug,
      brand_id: brandId,
      brand,
      category_id: categoryId,
      category,
      subcategory: raw.subcategory,
      model: raw.model,
      description_short: raw.description_short,
      description_long: raw.description_long,
      price: raw.price,
      currency: raw.currency,
      availability: raw.availability,
      status: raw.status,
      featured: raw.featured,
      order: index + 1,
      specs: raw.specs || [],
      images,
      primary_image_url: primaryImage?.url,
      source_catalog: raw.source,
      notes: raw.notes,
      tags: [],
      created_at: '2025-01-01T00:00:00Z',
      updated_at: '2025-01-01T00:00:00Z',
    }
  })
}

export const STATIC_PRODUCTS: Product[] = buildProducts()

// Helper functions
export function getProductBySlug(slug: string): Product | undefined {
  return STATIC_PRODUCTS.find(p => p.slug === slug && p.status === 'published')
}

export function getProductsByCategory(categorySlug: string): Product[] {
  const category = STATIC_CATEGORIES.find(c => c.slug === categorySlug)
  if (!category) return []
  return STATIC_PRODUCTS.filter(p => p.category_id === category.id && p.status === 'published')
}

export function getFeaturedProducts(): Product[] {
  return STATIC_PRODUCTS.filter(p => p.featured && p.status === 'published')
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  return STATIC_PRODUCTS
    .filter(p => p.id !== product.id && p.status === 'published' &&
      (p.category_id === product.category_id || p.brand_id === product.brand_id))
    .slice(0, limit)
}

export function searchProducts(query: string, filters?: { category?: string; brand?: string }): Product[] {
  const q = query.toLowerCase()
  return STATIC_PRODUCTS.filter(p => {
    if (p.status !== 'published') return false
    if (filters?.category) {
      const cat = STATIC_CATEGORIES.find(c => c.slug === filters.category)
      if (cat && p.category_id !== cat.id) return false
    }
    if (filters?.brand) {
      const brand = STATIC_BRANDS.find(b => b.slug === filters.brand)
      if (brand && p.brand_id !== brand.id) return false
    }
    if (!q) return true
    return (
      p.name.toLowerCase().includes(q) ||
      p.model?.toLowerCase().includes(q) ||
      p.brand?.name.toLowerCase().includes(q) ||
      p.description_short?.toLowerCase().includes(q) ||
      p.category?.name.toLowerCase().includes(q)
    )
  })
}

export function getDashboardStats() {
  return {
    totalProducts: STATIC_PRODUCTS.length,
    publishedProducts: STATIC_PRODUCTS.filter(p => p.status === 'published').length,
    draftProducts: STATIC_PRODUCTS.filter(p => p.status === 'draft').length,
    featuredProducts: STATIC_PRODUCTS.filter(p => p.featured).length,
    totalCategories: STATIC_CATEGORIES.length,
    totalBrands: STATIC_BRANDS.length,
  }
}
